const _dpCache = new Map();
function dparts(d) {
  let p = _dpCache.get(d);
  if (p) return p;
  const dt = new Date(EPOCH + d * 86400000);
  p = { y: dt.getUTCFullYear(), m: dt.getUTCMonth(), dom: dt.getUTCDate(), dow: dt.getUTCDay() };
  if (_dpCache.size > 5000) _dpCache.clear();
  _dpCache.set(d, p);
  return p;
}
function fmtDate(d, opt = {}) {
  const p = dparts(d);
  const s = `${MONTHS[p.m]} ${p.dom}, ${p.y}`;
  return opt.dow ? `${DOW[p.dow]} ${s}` : s;
}
